// Bundles icons/*.svg (Lucide, ISC, see icons/LICENSE-lucide.txt) into
// icons.js so scenes can inline them with icon("pencil", { size, stroke }).
// Add an icon: download it from unpkg.com/lucide-static@0.460.0/icons/<name>.svg
// into icons/, then run: npm run icons
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const dir = path.join(root, "icons");
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const src = fs.readFileSync(path.join(dir, f), "utf8");
  const inner = src.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>[\s\S]*$/, "");
  out[f.replace(/\.svg$/, "")] = inner.replace(/\s+/g, " ").trim();
}
const js = `// GENERATED by scripts/build-icons.cjs from icons/*.svg. Do not edit.
// Lucide icons, ISC licence (icons/LICENSE-lucide.txt).
const ICONS = ${JSON.stringify(out, null, 2)};

// icon(name, { size = 48, stroke = 2.75, className = "" })
// Thick default stroke so icons survive a projector.
const icon = (name, opts = {}) => {
  const size = opts.size || 48;
  const stroke = opts.stroke || 2.75;
  return \`<svg class="icon \${opts.className || ""}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="\${stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${ICONS[name] || ""}</svg>\`;
};
`;
fs.writeFileSync(path.join(root, "icons.js"), js);
console.log(`icons.js: ${Object.keys(out).length} icons`);
